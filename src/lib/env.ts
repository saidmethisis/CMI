// Какое это окружение. Задаётся APP_ENV в env-файле окружения
// (.env.staging → staging, .env.production → production).
//
// Нужно, чтобы стейджинг вёл себя иначе там, где это критично:
//   • полностью закрыт от индексации (robots.ts) — иначе тестовая копия
//     попадёт в поиск и станет дублем боевого сайта;
//   • показывает плашку «это тестовая версия», чтобы редакция не перепутала
//     окружения и не написала настоящую новость не туда.
export const APP_ENV = process.env.APP_ENV || "production";
export const IS_STAGING = APP_ENV === "staging";
